package com.aquamonitor.platform.u202418405.monitoring.domain.model.aggregates;

import com.aquamonitor.platform.u202418405.monitoring.domain.model.commands.CreateSamplingPlanCommand;
import com.aquamonitor.platform.u202418405.monitoring.domain.model.valueobjects.*;
import lombok.Getter;
import java.time.Instant;

/**
 * Aggregate root that represents a water sampling plan.
 * @author Jean Pierre Condor Sandoval
 */
@Getter
public class SamplingPlan {
    private Long id;
    private final PlanCode planCode;
    private final StationId stationId;
    private final SamplingWindow samplingWindow;
    private final SampleVolume sampleVolume;
    private final Integer priorityLevel;
    private final SamplingPlanStatus status;
    private final String samplingNotes;
    private final Instant createdAt;
    private final Instant updatedAt;
    /**
     * Creates a new sampling plan from a command. createdAt and updatedAt receive the same instant.
     *
     * @param command the create command
     * @throws IllegalArgumentException if a business rule is violated
     */

    public SamplingPlan(CreateSamplingPlanCommand command) {

        this(null, command.planCode(), command.stationId(), command.samplingWindow(),

                command.sampleVolume(), command.priorityLevel(), command.status(),

                command.samplingNotes(), Instant.now(), null);

    }


    /**
     * Rebuilds a sampling plan from stored data.
     * @param id        the generated id
     * @param createdAt creation instant
     * @param updatedAt last update instant
     * @return the rebuilt sampling plan
     */
    public SamplingPlan(Long id, PlanCode planCode, StationId stationId, SamplingWindow samplingWindow,
                        SampleVolume sampleVolume, Integer priorityLevel, SamplingPlanStatus status,
                        String samplingNotes, Instant createdAt, Instant updatedAt) {

        if (planCode == null) throw new IllegalArgumentException("Plan code must not be null");
        if (stationId == null) throw new IllegalArgumentException("Station id must not be null");
        if (samplingWindow == null) throw new IllegalArgumentException("Sampling window must not be null");
        if (sampleVolume == null) throw new IllegalArgumentException("Sample volume must not be null");
        if (priorityLevel == null || priorityLevel < 1 || priorityLevel > 5) {
            throw new IllegalArgumentException("Priority level must be between 1 and 5");
        }

        if (status == null) throw new IllegalArgumentException("Status must not be null");
        this.id = id;
        this.planCode = planCode;
        this.stationId = stationId;
        this.samplingWindow = samplingWindow;
        this.sampleVolume = sampleVolume;
        this.priorityLevel = priorityLevel;
        this.status = status;
        this.samplingNotes = samplingNotes;
        this.createdAt = createdAt;
        this.updatedAt = updatedAt != null ? updatedAt : createdAt;
    }

    /**
     * Assigns the id generated by persistence.
     * @param id the generated id
     */
    public void assignId(Long id) {
        this.id = id;
    }
}